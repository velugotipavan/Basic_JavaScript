//Arthametic operations  ++ Increment , -- Decrement,


// Pre increment  ++m
let m : number = 5;
console.log(++m)   // 6
console.log(m);    // 6

//Post increment  m++
let n : number = 5;
console.log(n++);  //5 
console.log(n);    //6

// Pre decrement
let p : number = 10;
console.log(--p);    // 9
console.log(p);      // 9

// post decrement 
let q : number = 10;
console.log(q--);  //10
console.log(q);    // 9