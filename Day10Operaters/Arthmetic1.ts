//Arthametic operations + Sum ,  - difference, * multiplication , / division, % Remainder, ++ Increment , -- Decrement,
//% is often called the modulus operator (or modulo operator), because it returns the remainder after division.

let m : number = 81;
let n : number = 9;
console.log("The sum of M and N is : " +(m+n));   
console.log("The differnece of M and N is : " +(m-n));
console.log("The division of M and N is : " +(m/n));     // 81/9
console.log("The mutliplication of M and N is : " +(m*n));
console.log("The Reminder / module of M and N is : " +(m%n));   //  81%9 ---> sesham / Reminder = 0

